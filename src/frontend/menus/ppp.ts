import type { FieldSpec } from "./types";

const profile = (key = "profile") => ref(key, "ppp/profile");
const dialOut = (): FieldSpec[] => [
  text("user"),
  secret("password"),
  profile(),
  check("add-default-route"),
  num("default-route-distance"),
  check("use-peer-dns"),
  check("dial-on-demand"),
  text("allow", {
    options: ["mschap2", "mschap2,mschap1", "mschap2,mschap1,chap,pap"],
  }),
  num("max-mtu"),
  num("max-mru"),
  comment(),
];

const server = (path: string, extra: FieldSpec[] = []) =>
  form(path, [
    check("enabled"),
    profile("default-profile"),
    text("authentication", {
      options: ["mschap2", "mschap2,mschap1", "mschap2,mschap1,chap,pap"],
    }),
    ...extra,
    num("max-mtu"),
    num("max-mru"),
    text("keepalive-timeout"),
  ]);

