// The wifi package of RouterOS 7.13+ (wifiwave2 before), and its CAPsMAN.

export function wifiTabs(base: "interface/wifi" | "interface/wifiwave2") {
  const r = (path: string) => `${base}/${path}`;
  return tabs(
    [
      "wifiInterfaces",
      table(
        base,
        [
          "name",
          "master-interface",
          "configuration.ssid",
          "configuration.mode",
          "channel.band",
          "channel.frequency",
          "channel.width",
          "security",
          "running",
        ],
        [
          name(),
          ref("master-interface", base, { hintKey: "hints.virtualAp" }),
          ref("configuration", r("configuration")),
          text("configuration.ssid"),
          select("configuration.mode", ["ap", "station", "station-bridge"]),
          text("configuration.country"),
          ref("channel", r("channel")),
          text("channel.band", {
            options: [
              "2ghz-g",
              "2ghz-n",
              "2ghz-ax",
              "5ghz-a",
              "5ghz-n",
              "5ghz-ac",
              "5ghz-ax",
              "6ghz-ax",
            ],
          }),
          text("channel.width", {
            options: [
              "20mhz",
              "20/40mhz",
              "20/40mhz-Ce",
              "20/40mhz-eC",
              "20/40/80mhz",
              "20/40/80/160mhz",
              "20/40/80+80mhz",
            ],
          }),
          text("channel.frequency"),
          ref("security", r("security")),
          text("security.authentication-types", {
            options: [
              "wpa2-psk",
              "wpa3-psk",
              "wpa2-psk,wpa3-psk",
              "wpa2-eap",
              "wpa3-eap",
            ],
          }),
          secret("security.passphrase"),
          ref("datapath", r("datapath")),
          ref("datapath.bridge", "interface/bridge"),
          ref("steering", r("steering")),
          text("mac-address"),
          comment(),
        ],
        { refreshMs: 5000 },
      ),
    ],
    [
      "wifiConfigurations",
      table(
        r("configuration"),
        [
          "name",
          "ssid",
          "mode",
          "country",
          "security",
          "channel",
          "datapath",
          "manager",
        ],
        [
          name(),
          text("ssid"),
          select("mode", ["ap", "station", "station-bridge"]),
          text("country"),
          ref("security", r("security")),
          ref("channel", r("channel")),
          ref("datapath", r("datapath")),
          ref("steering", r("steering")),
          select("manager", ["local", "capsman", "capsman-or-local"]),
          check("hide-ssid"),
          text("tx-power"),
          comment(),
        ],
      ),
    ],
    [
      "wifiSecurity",
      table(
        r("security"),
        [
          "name",
          "authentication-types",
          "encryption",
          "wps",
          "ft",
          "management-protection",
        ],
        [
          name(),
          text("authentication-types", {
            options: [
              "wpa2-psk",
              "wpa3-psk",
              "wpa2-psk,wpa3-psk",
              "wpa2-eap",
              "wpa3-eap",
            ],
          }),
          secret("passphrase"),
          text("encryption", { options: ["ccmp", "gcmp", "ccmp,gcmp"] }),
          select("wps", ["push-button", "disable"]),
          check("ft"),
          check("ft-over-ds"),
          select("management-protection", ["allowed", "disabled", "required"]),
          check("disable-pmkid"),
          text("group-key-update"),
          comment(),
        ],
      ),
    ],
    [
      "wifiChannels",
      table(
        r("channel"),
        ["name", "band", "width", "frequency", "skip-dfs-channels"],
        [
          name(),
          text("band", {
            options: [
              "2ghz-g",
              "2ghz-n",
              "2ghz-ax",
              "5ghz-a",
              "5ghz-n",
              "5ghz-ac",
              "5ghz-ax",
              "6ghz-ax",
            ],
          }),
          text("width", {
            options: ["20mhz", "20/40mhz", "20/40/80mhz", "20/40/80/160mhz"],
          }),
          text("frequency"),
          select("skip-dfs-channels", ["all", "10min-cac", "disabled"]),
          text("secondary-frequency"),
          comment(),
        ],
      ),
    ],
    [
      "wifiDatapaths",
      table(
        r("datapath"),
        ["name", "bridge", "vlan-id", "client-isolation"],
        [
          name(),
          ref("bridge", "interface/bridge"),
          num("vlan-id"),
          check("client-isolation"),
          num("bridge-cost"),
          text("bridge-horizon"),
          comment(),
        ],
      ),
    ],
    [
      "wifiSteering",
      table(
        r("steering"),
        ["name", "neighbor-group", "rrm", "wnm"],
        [name(), text("neighbor-group"), check("rrm"), check("wnm"), comment()],
      ),
    ],
    [
      "accessList",
      table(
        r("access-list"),
        [
          "mac-address",
          "interface",
          "ssid-regexp",
          "signal-range",
          "action",
          "vlan-id",
        ],
        [
          text("mac-address"),
          ref("interface", base, { extra: ["any"] }),
          text("ssid-regexp"),
          text("signal-range"),
          select("action", ["accept", "reject", "query-radius"]),
          num("vlan-id"),
          secret("passphrase"),
          text("time"),
          comment(),
        ],
        { ordered: true },
      ),
    ],
    [
      "registration",
      table(
        r("registration-table"),
        [
          "interface",
          "mac-address",
          "ssid",
          "signal",
          "band",
          "tx-rate",
          "rx-rate",
          "uptime",
          "bytes",
        ],
        [],
        { noAdd: true, noEdit: true, noToggle: true, refreshMs: 3000 },
      ),
    ],
    [
      "wifiProvisioning",
      table(
        r("provisioning"),
        [
          "action",
          "supported-bands",
          "identity-regexp",
          "address-ranges",
          "master-configuration",
          "slave-configurations",
          "name-format",
        ],
        [
          select("action", [
            "create-enabled",
            "create-disabled",
            "create-dynamic-enabled",
            "none",
          ]),
          text("supported-bands"),
          text("identity-regexp"),
          text("common-name-regexp"),
          text("address-ranges"),
          ref("master-configuration", r("configuration"), { required: true }),
          ref("slave-configurations", r("configuration")),
          text("name-format"),
          comment(),
        ],
        { ordered: true },
      ),
    ],
    [
      "capsmanManager",
      form(r("capsman"), [
        check("enabled"),
        iface("interfaces", { extra: ["all"] }),
        text("ca-certificate"),
        text("certificate"),
        check("require-peer-certificate"),
        select("upgrade-policy", [
          "none",
          "require-same-version",
          "suggest-same-version",
        ]),
        text("package-path"),
      ]),
    ],
    [
      "remoteCaps",
      table(
        r("capsman/remote-cap"),
        [
          "identity",
          "address",
          "common-name",
          "version",
          "state",
          "board-name",
        ],
        [],
        {
          noAdd: true,
          noEdit: true,
          noToggle: true,
          refreshMs: 10000,
          actions: [
            action("provision", "provision", { perRow: true }),
            action("upgrade", "upgrade", { perRow: true }),
          ],
        },
      ),
    ],
    [
      "wifiCap",
      form(
        r("cap"),
        [
          check("enabled"),
          ifaceList("discovery-interfaces"),
          text("caps-man-addresses"),
          text("caps-man-names"),
          ref("slaves-datapath", r("datapath")),
          text("certificate"),
          check("lock-to-caps-man"),
        ],
        { status: ["requested-certificate", "locked-caps-man-common-name"] },
      ),
    ],
  );
}

