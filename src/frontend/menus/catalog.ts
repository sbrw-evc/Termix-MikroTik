const leaf = (
  id: string,
  view: MenuNode["view"],
  requires?: MenuNode["requires"],
  icon?: MenuNode["icon"],
): MenuNode => ({
  id,
  labelKey: `menu.${id}`,
  view,
  requires,
  icon,
});

const group = (
  id: string,
  icon: MenuNode["icon"],
  children: MenuNode[],
  requires?: MenuNode["requires"],
): MenuNode => ({
  id,
  labelKey: `menu.${id}`,
  icon,
  children,
  requires,
});

