/** The menu entry with this id, wherever it sits. */
export function findMenu(
  id: string,
  nodes: MenuNode[] = MENU,
): MenuNode | null {
  for (const node of nodes) {
    if (node.id === id) return node;
    if (node.children) {
      const found = findMenu(id, node.children);
      if (found) return found;
    }
  }
  return null;
}
